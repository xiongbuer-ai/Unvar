import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import type { Store } from '../packages/db/src/index';
import { FindingWorkflow } from '../packages/workflows/src/finding';
import type { LLMProvider } from '../packages/llm/src/index';
import type { FindingCandidate } from '../packages/shared/src/finding';

export async function verifyFindings(store: Store) {
  const experiment = store.lab.list().find(item => ['done', 'archived'].includes(item.status))!;
  assert.ok(experiment);
  const config = store.saveProvider({ providerType: 'openai-compatible', displayName: 'Finding mock', baseUrl: 'https://example.com/v1', model: 'mock:finding', enabled: true });
  const candidate: FindingCandidate = { text: 'The tested transaction prevented partial writes.', confidence: 'medium', counterEvidence: 'Only one local version tested.', evidence: [{ experimentId: experiment.id, relation: 'supports', note: 'No partial rows survived.' }] };
  let calls = 0;
  const provider: LLMProvider = { id: config.id, name: 'mock:finding', generateText: async () => ({ text: '', model: 'mock:finding' }), generateStructured: async ({ schema }) => { calls++; return schema.parse(candidate); } };
  const workflow = new FindingWorkflow(store, 'test prompt');
  const input = () => ({ experimentIds: [experiment.id], providerId: config.id, operationId: randomUUID() });
  const request = input(); const first = workflow.start(request, provider);
  assert.equal(workflow.start(request, provider).id, first.id);
  await workflow.waitForIdle();
  assert.equal(calls, 1);
  assert.equal(store.findings.run(first.id).status, 'completed');
  let finding = store.findings.get(store.findings.run(first.id).findingId!);
  assert.equal(finding.status, 'candidate'); assert.equal(finding.confirmedAt, null);
  assert.deepEqual(finding.aiProposal, candidate);
  assert.equal(workflow.start(request, provider).id, first.id); assert.equal(calls, 1);
  assert.throws(() => workflow.start({ ...request, experimentIds: ['01ARZ3NDEKTSV4RRFFQ69G5FAV'] }, provider));
  const edit = { id: finding.id, revision: finding.revision, text: candidate.text, confidence: candidate.confidence, counterEvidence: candidate.counterEvidence, evidence: [], reason: 'Remove unverified evidence.' };
  finding = store.findings.edit(edit);
  assert.throws(() => store.findings.review({ id: finding.id, revision: finding.revision, action: 'accept', reason: 'Reviewed.' }));
  assert.throws(() => store.findings.edit({ ...edit, revision: 0 }));
  finding = store.findings.edit({ ...edit, revision: finding.revision, evidence: candidate.evidence, reason: 'Checked the recorded experiment result.' });
  store.db.exec("CREATE TEMP TRIGGER finding_fail_decision BEFORE INSERT ON decisions BEGIN SELECT RAISE(ABORT,'injected'); END;");
  assert.throws(() => store.findings.review({ id: finding.id, revision: finding.revision, action: 'accept', reason: 'Confirmed evidence.' }));
  assert.equal(store.findings.get(finding.id).status, 'candidate');
  assert.throws(() => store.findings.edit({ ...edit, revision: finding.revision }));
  assert.equal(store.findings.get(finding.id).evidence.length, 1);
  store.db.exec('DROP TRIGGER finding_fail_decision');
  const review = { id: finding.id, revision: finding.revision, action: 'accept' as const, reason: 'I verified the linked result and its limitations.' };
  finding = store.findings.review(review); assert.ok(finding.confirmedAt); assert.equal(finding.status, 'accepted');
  store.findings.review(review); // Retry of the same completed review must not create another decision.
  assert.equal((store.db.prepare("SELECT COUNT(*) AS n FROM decisions WHERE entity_id=? AND type='finding_confirmation'").get(finding.id) as { n: number }).n, 1);
  finding = store.findings.edit({ ...edit, revision: finding.revision, text: 'A narrower human conclusion.', evidence: candidate.evidence, reason: 'Avoid generalizing from one test.' });
  assert.equal(finding.status, 'candidate'); assert.equal(finding.confirmedAt, null); assert.equal(finding.aiProposal.text, candidate.text);
  const rejected = store.findings.review({ id: finding.id, revision: finding.revision, action: 'reject', reason: 'Need more experiments.' });
  assert.equal(rejected.status, 'archived');

  const canceled = workflow.start(input(), provider); workflow.cancel(canceled.id); await workflow.waitForIdle();
  assert.equal(store.findings.run(canceled.id).status, 'canceled');
  const bad: LLMProvider = { ...provider, generateStructured: async () => ({ ...candidate, status: 'accepted' }) as never };
  const failed = workflow.start(input(), bad); await workflow.waitForIdle();
  assert.equal(store.findings.run(failed.id).status, 'failed'); assert.equal(store.findings.run(failed.id).findingId, null);
  const invented = workflow.start(input(), { ...provider, generateStructured: async () => ({ ...candidate, evidence: [{ ...candidate.evidence[0], experimentId: '01ARZ3NDEKTSV4RRFFQ69G5FAV' }] }) as never });
  await workflow.waitForIdle(); assert.equal(store.findings.run(invented.id).status, 'failed');
  const slow = new FindingWorkflow(store, '', 5);
  const timeout = slow.start(input(), { ...provider, generateStructured: () => new Promise(() => {}) });
  await slow.waitForIdle(); assert.equal(store.findings.run(timeout.id).status, 'failed'); assert.match(store.findings.run(timeout.id).error!, /timed out/);
  const countBeforeFailure = store.findings.list().length;
  store.db.exec("CREATE TEMP TRIGGER finding_fail_evidence BEFORE INSERT ON finding_evidence BEGIN SELECT RAISE(ABORT,'injected'); END;");
  const storageFailure = workflow.start(input(), provider); await workflow.waitForIdle();
  assert.equal(store.findings.run(storageFailure.id).status, 'failed');
  assert.equal(store.findings.run(storageFailure.id).findingId, null);
  assert.equal(store.findings.list().length, countBeforeFailure);
  store.db.exec('DROP TRIGGER finding_fail_evidence');
  const retry = workflow.start(input(), provider); await workflow.waitForIdle();
  assert.equal(store.findings.run(retry.id).status, 'completed');
  const recovered = store.findings.start(input()); store.findings.recover(); assert.equal(store.findings.run(recovered.id).status, 'failed');
  const pending = store.lab.list().find(item => item.status === 'running')!;
  assert.throws(() => workflow.start({ ...input(), experimentIds: [pending.id] }, provider));
  console.log('Finding integration passed: candidate-only generation, human evidence/review gates, atomic decisions, stale edits, confirmation invalidation, cancellation/timeout/retry, idempotency and recovery.');
  return finding.id;
}
