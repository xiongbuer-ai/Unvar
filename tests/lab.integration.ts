import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { LabRepository, type Store } from '../packages/db/src/index';
import { experimentInputSchema } from '../packages/shared/src/lab';
import { experimentMarkdown } from '../apps/desktop/src/main/markdown';

export function verifyLab(store: Store): string {
  let clock = Date.now();
  const lab = new LabRepository(store.db, () => clock);
  const id = store.radar.createExperiment(store.radar.listQuestions()[0].id).id;
  let item = lab.get(id);
  const fields = { id, revision: item.revision, title: 'Failure injection', prediction: 'I expect both writes to roll back.', baseline: 'Two independent writes', method: 'Inject a second-write failure', metrics: 'Number of surviving rows', result: '', limitations: '', trust: null, humanTimeMinutes: 0, interventionCount: 0, bugCount: 0, reworkCount: 0 };
  assert.equal(item.prediction, '');
  assert.throws(() => lab.transition({ id, revision: item.revision, status: 'running' }));
  assert.throws(() => lab.transition({ id, revision: item.revision, status: 'ready' }));
  assert.equal(experimentInputSchema.safeParse({ ...fields, generatedPrediction: true }).success, false);
  item = lab.save(fields);
  assert.throws(() => lab.save({ ...fields, title: 'Stale edit' }));
  store.db.exec("CREATE TEMP TRIGGER fail_lab_log BEFORE INSERT ON experiment_logs BEGIN SELECT RAISE(ABORT,'injected'); END;");
  assert.throws(() => lab.save({ ...fields, revision: item.revision, title: 'Must roll back' }));
  assert.equal(lab.get(id).title, fields.title);
  store.db.exec('DROP TRIGGER fail_lab_log');
  item = lab.transition({ id, revision: item.revision, status: 'ready' });
  item = lab.transition({ id, revision: item.revision, status: 'running' });
  const started = item.timerStartedAt;
  clock += 65000;
  assert.equal(lab.get(id).elapsedSeconds, 65);
  assert.equal(new LabRepository(store.db, () => clock).get(id).elapsedSeconds, 65);
  assert.throws(() => lab.save({ ...fields, revision: item.revision, prediction: 'Changed after observing result' }));
  lab.timer({ id, action: 'pause' }); lab.timer({ id, action: 'pause' });
  clock += 5000;
  assert.equal(lab.get(id).elapsedSeconds, 65);
  lab.timer({ id, action: 'start' }); clock += 10000;
  assert.equal(lab.get(id).elapsedSeconds, 75);
  const note = { experimentId: id, operationId: randomUUID(), text: 'Observed no partial rows after failure.' };
  lab.appendLog(note); lab.appendLog(note);
  assert.equal(lab.logs(id).filter(log => log.text === note.text).length, 1);
  assert.throws(() => lab.appendLog({ ...note, text: 'Different content, reused operation id' }));
  assert.throws(() => lab.transition({ id, revision: item.revision, status: 'analyzing' }));
  item = lab.save({ ...fields, revision: item.revision, result: 'No partial rows survived.' });
  item = lab.transition({ id, revision: item.revision, status: 'analyzing' });
  assert.equal(item.timerStartedAt, null);
  assert.equal(item.startedAt, started);
  assert.throws(() => lab.transition({ id, revision: item.revision, status: 'done' }));
  item = lab.save({ ...fields, revision: item.revision, result: 'No partial rows survived.', limitations: 'Only one database version tested.', trust: 3 });
  item = lab.transition({ id, revision: item.revision, status: 'done' });
  const logCount = lab.logs(id).length;
  lab.transition({ id, revision: 0, status: 'done' });
  assert.equal(lab.logs(id).length, logCount);
  assert.throws(() => lab.save({ ...fields, revision: item.revision }));
  const markdown = experimentMarkdown(item, lab.logs(id));
  assert.ok(markdown.includes(fields.prediction)); assert.ok(markdown.includes(item.signalId)); assert.ok(markdown.includes(note.text));
  lab.transition({ id, revision: item.revision, status: 'archived' });

  const another = store.radar.listQuestions().find(question => question.id !== item.questionId)!;
  const recoveryId = store.radar.createExperiment(another.id).id;
  let recovery = lab.get(recoveryId);
  recovery = lab.save({ ...fields, id: recoveryId, revision: recovery.revision });
  recovery = lab.transition({ id: recoveryId, revision: recovery.revision, status: 'ready' });
  lab.transition({ id: recoveryId, revision: recovery.revision, status: 'running' });
  lab.appendLog({ experimentId: recoveryId, operationId: randomUUID(), text: 'Must survive a full database restart.' });
  console.log('Lab integration passed: transitions, human Prediction lock, stale edits, atomic rollback, timer pause/resume, idempotent logs and Markdown provenance.');
  return recoveryId;
}
